/**
 * Polylines (mm) of a text string.
 * @param h character height in mm; (x, y) top-left; rot 0 | 90 (reads bottom → top)
 */
export function textStrokes(text, x, y, h = 1.2, rot = 0) {
  const s = h / 6, adv = 5.6 * s, out = [];
  [...String(text).toUpperCase()].forEach((ch, i) => {
    for (const line of G[ch] || (ch === ' ' ? [] : G['#'])) {
      out.push(line.map(([gx, gy]) => {
        const lx = i * adv + gx * s, ly = gy * s;
        return rot === 90 ? [x + ly, y - lx] : [x + lx, y + ly];
      }));
    }
  });
  return out;
}
export const textWidth = (text, h = 1.2) => String(text).length * 5.6 * (h / 6) - 1.6 * (h / 6);
